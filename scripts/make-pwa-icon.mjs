import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync( "public/stairway.svg", "utf8" );
const points = src.match( /points="([^"]+)"/ )[ 1 ];

// Glyph bbox inside the 512 viewBox, measured from the polygon itself.
const nums = points.trim().split( /\s+/ ).map( Number );
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
for ( let i = 0; i < nums.length; i += 2 ) {
	minX = Math.min( minX, nums[ i ] );
	maxX = Math.max( maxX, nums[ i ] );
	minY = Math.min( minY, nums[ i + 1 ] );
	maxY = Math.max( maxY, nums[ i + 1 ] );
}

// Target a 312px box (~61% of 512) so the mark sits inside the maskable
// safe circle while still reading well as a plain `any` icon.
const TARGET = 312;
const scale = Math.min( TARGET / ( maxX - minX ), TARGET / ( maxY - minY ) );
const tx = 256 - ( minX * scale + ( maxX - minX ) * scale / 2 );
const ty = 256 - ( minY * scale + ( maxY - minY ) * scale / 2 );

console.log( `bbox x[${ minX }, ${ maxX }] y[${ minY }, ${ maxY }]` );
console.log( `scale ${ scale } translate(${ tx.toFixed( 2 ) } ${ ty.toFixed( 2 ) })` );

const out = `<?xml version="1.0" encoding="UTF-8"?>
<!--
	The installable app icon. Deliberately NOT public/stairway.svg: that file is
	load-bearing as a CSS mask (see shared/ui/components/logo.tsx), so it carries
	no fill and no plate and would render as an invisible black-on-transparent
	square in a launcher.

	The plate is the neutral-dark palette value and the mark is the apple accent.
	Both are fixed values, not theme variables, because an installed icon is
	baked once while the user can still pick any of the ten palettes later.

	Generated by scripts/make-pwa-icon.mjs — edit that, not this.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
	<rect width="512" height="512" fill="#1F1F1F"/>
	<g transform="translate(${ tx.toFixed( 2 ) } ${ ty.toFixed( 2 ) }) scale(${ scale.toFixed( 6 ) })">
		<polygon fill="#FF6B6B" points="${ points }"/>
	</g>
</svg>
`;

writeFileSync( "public/pwa-icon.svg", out );
console.log( "wrote public/pwa-icon.svg" );
